export function normalizeComparisonPresentationLocale(
    locale
) {
    if (
        typeof locale !== "string"
    ) {
        return "en";
    }

    const normalized =
        locale
            .trim()
            .toLowerCase()
            .replace(/_/g, "-");

    if (
        normalized === "zh" ||
        normalized === "zh-cn" ||
        normalized === "zh-sg" ||
        normalized === "zh-hans"
    ) {
        return "zh-CN";
    }

    if (
        normalized === "zh-hk" ||
        normalized === "zh-mo" ||
        normalized === "zh-hant" ||
        normalized === "zh-tc" ||
        normalized === "zh-tw"
    ) {
        return "zh-HK";
    }

    if (
        normalized === "fr" ||
        normalized.startsWith("fr-")
    ) {
        return "fr";
    }

    if (
        normalized === "es" ||
        normalized.startsWith("es-")
    ) {
        return "es";
    }

    if (
        normalized === "ja" ||
        normalized.startsWith("ja-")
    ) {
        return "ja";
    }

    return "en";
}


export function getComparisonPresentation(
    locale
) {
    const canonical =
        normalizeComparisonPresentationLocale(
            locale
        );

    return (
        COMPARISON_I18N[canonical] ??
        COMPARISON_I18N.en
    );
}


export function comparisonText(
    locale,
    key,
    fallback = ""
) {
    const dictionary =
        getComparisonPresentation(
            locale
        );

    const value =
        dictionary[key];

    return (
        typeof value === "string"
            ? value
            : fallback
    );
}


